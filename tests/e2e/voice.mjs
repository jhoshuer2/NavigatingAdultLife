import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--use-gl=angle', '--autoplay-policy=no-user-gesture-required'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
page.setDefaultTimeout(10000)
const errors = []; page.on('pageerror', (e) => errors.push(String(e)))
const reqs = []; page.on('response', (r) => { if (r.url().includes('/voice/')) reqs.push(`${r.status()} ${r.url().split('/voice/')[1]}`) })
await page.addInitScript(() => { window.__plays = []; const P = HTMLMediaElement.prototype.play; HTMLMediaElement.prototype.play = function () { window.__plays.push(this.src.slice(0, 20)); return P.call(this) } })
await page.goto(`${process.env.BASE ?? 'http://localhost:4173'}/?unlimited=1&debug=1&howto=1`)
await page.waitForFunction(() => window.__nal)
await page.locator('button.btn:has-text("Play")').first().click()
await page.evaluate(() => { const g = window.__nal.useGame; g.setState({ meta: { ...g.getState().meta, seenTutorial: true } }); g.getState().setLang('pcm') })
await page.evaluate(() => window.__nal.jump(17, 'scholar', 3)); await page.waitForTimeout(3000)
console.log(reqs, await page.evaluate(() => window.__plays))
if (!reqs.some((r) => r.startsWith('200 sug_study.pcm.mp3'))) throw new Error('expected the study suggestion clip in Pidgin')
await page.evaluate(() => window.__nal.useGame.getState().startJog()); await page.waitForTimeout(2500)
console.log(reqs.filter((r) => r.includes('how_')))
if (!reqs.some((r) => r.includes('how_jog.pcm.mp3'))) throw new Error('expected the jog how-to clip')
console.log('errors', errors)
await browser.close()
