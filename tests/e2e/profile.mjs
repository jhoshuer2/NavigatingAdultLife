import { chromium } from 'playwright-core'
const OUT = process.env.OUT ?? '/tmp/claude-0/-home-user-NavigatingAdultLife/f97bb3da-afd4-5501-b372-1bb1d534ad7b/scratchpad/shots'
const browser = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
page.setDefaultTimeout(8000)
const errors = []; page.on('pageerror', (e) => errors.push(String(e)))
await page.goto(`${process.env.BASE ?? 'http://localhost:5174'}/?unlimited=1&debug=1`)
await page.waitForFunction(() => window.__nal)
await page.evaluate(() => window.__nal.useGame.getState().go('settings'))
await page.getByText('Online profile').scrollIntoViewIfNeeded()
await page.getByPlaceholder('Pick a name').fill('Tobi')
await page.getByRole('button', { name: /Create profile/ }).click()
await page.getByText('Recovery code').first().waitFor()
await page.screenshot({ path: `${OUT}/300-profile-created.png` })
const code = await page.locator('.tracking-widest.select-all').innerText()
console.log('code', code)
await page.getByRole('button', { name: /I saved it/ }).click()
await page.getByRole('button', { name: /Sign out$/ }).click()
await page.getByRole('button', { name: /I have a code/ }).click()
await page.getByPlaceholder('XXXX-XXXX-XXXX-XXXX').fill(code)
await page.getByRole('button', { name: /Restore/ }).click()
await page.getByText(/Tobi#/).waitFor()
console.log('restored ok')
await page.screenshot({ path: `${OUT}/301-profile-restored.png` })
console.log('errors', errors)
await browser.close()
